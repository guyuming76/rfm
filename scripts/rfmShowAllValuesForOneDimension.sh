 # 遍历每个目录部分
 for part in "${dir_parts[@]}"; do
 # 构建到当前部分的完整路径
 temp_path="$temp_path/$part"
 
 # 检查这个路径是否是符号链接
 if [[ -L "$temp_path" ]]; then
 # 如果是符号链接，停止添加后续部分
